<?php
/**
 * ============================================================================
 * auth_check.php — حماية الصفحات حسب صلاحية المستخدم
 * ============================================================================
 * ملاحظات:
 * - الجلسة (Session) تحفظ هوية المستخدم بعد تسجيل الدخول.
 * - قبل فتح صفحة حساسة (مثل لوحة الإدارة) يتم التحقق من الصلاحية.
 * - إذا لم يكن المستخدم مخولاً يتم توجيهه إلى login.php مع إيقاف تنفيذ الصفحة.
 * ============================================================================
 */

// نحمّل التهيئة (جلسة + اتصال قاعدة البيانات + دوال الأمان)
require_once 'init.php';

/**
 * تقييد الوصول للمسؤول فقط (Admin)
 * تُستدعى في صفحات مثل: admin_dashboard.php
 */
function restrictToAdmin() {
    // الشرط: يجب وجود user_id في الجلسة وأن يكون الدور admin
    if (!isset($_SESSION['user_id']) || $_SESSION['user_role'] !== 'admin') {
        // غير مخول → تحويل لصفحة تسجيل الدخول
        header("Location: login.php");
        // مهم جداً: exit يمنع استمرار تنفيذ باقي كود الصفحة بعد التحويل
        exit();
    }
}

/**
 * تقييد الوصول لأي مستخدم مسجّل دخول فقط
 * مفيدة لصفحات مثل الحساب الشخصي أو إتمام الطلب مستقبلاً
 */
function restrictToLoggedIn() {
    // إذا لم يوجد معرف مستخدم في الجلسة فهو زائر غير مسجل
    if (!isset($_SESSION['user_id'])) {
        header("Location: login.php");
        exit();
    }
}
