<?php
/**
 * ============================================================================
 * logout.php — تسجيل الخروج من النظام
 * ============================================================================
 * ملاحظات:
 * 1) بدء الجلسة للوصول إلى بياناتها.
 * 2) تفريغ بيانات الجلسة ثم تدميرها بالكامل.
 * 3) تحويل المستخدم إلى صفحة تسجيل الدخول.
 * ============================================================================
 */

// بدء الجلسة إن لم تكن قد بدأت
if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

// تفريغ كل المتغيرات المحفوظة داخل الجلسة (مثل user_id و user_role)
$_SESSION = [];

// تدمير ملف الجلسة من السيرفر
session_destroy();

// بعد الخروج نعيد المستخدم لصفحة الدخول
header("Location: login.php");
exit();
